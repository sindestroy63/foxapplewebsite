export function getStoryForProduct(product: Product): ProductStoryData | null {
  const pick = (key: string): ProductStoryData | null => STORIES[key] || null
  const numericId = Number(product.id)
  if (Number.isFinite(numericId) && PRODUCT_MAP[numericId]) {
    const key = PRODUCT_MAP[numericId]
    return pick(key) || null
  }
  const str = `${product.slug || ""} ${product.name || ""} ${product.model || ""}`.toLowerCase()

  if (/ipad.*air/i.test(str)) return pick("ipad-air-m4")
  if (/ipad.*11|a16.*2025/i.test(str)) return pick("ipad-11")
  if (/watch.*series.*11/i.test(str)) return pick("watch-series-11")
  if (/watch.*se|se.*2025/i.test(str)) return pick("watch-se-3")
  if (/macbook.*neo|a18\s*pro/i.test(str)) return pick("macbook-neo")
  if (/macbook.*air|m5.*2026/i.test(str)) return pick("macbook-air-m5")
  if (/earpods.*usb|earpods.*type/i.test(str)) return pick("earpods-usbc")
  if (/earpods.*lightning/i.test(str)) return pick("earpods-lightning")
  if (/кабель|cable|usb-c.*lightning/i.test(str) && !/чехол|стекло/i.test(str)) return pick("apple-cable")
  if (/адаптер|charger|40-60w|20w/i.test(str) && !/чехол|стекло/i.test(str)) return pick("apple-adapter")
  if (/galaxy\s*buds|buds\s*4/.test(str)) {
    return /pro/.test(str) ? pick("galaxy-buds-pro") : pick("galaxy-buds")
  }
  if (/pixel\s*buds/.test(str)) return pick("pixel-buds")
  if (/galaxy\s*watch|часы\s*samsung|samsung\s+galaxy\s*watch/.test(str)) {
    if (/ultra/.test(str)) return pick("galaxy-watch-ultra")
    if (/classic/.test(str)) return pick("galaxy-watch-classic")
    if (/watch\s*9/.test(str)) return pick("galaxy-watch-9")
    return pick("galaxy-watch")
  }
  if (/homepod|home\s*pod/.test(str)) return pick("homepod-mini")
  if (/homeview|home\s*view/.test(str)) return pick("homeview")
  if (/яндекс|yandex/.test(str)) {
    if (/макс|\bmax\b/.test(str)) return pick("yandex-max")
    if (/мини|\bmini\b/.test(str)) return pick("yandex-mini")
    if (/миди|midi/.test(str)) return pick("yandex-midi")
    return pick("yandex-station")
  }
  if (/marshall/.test(str)) return pick("marshall")
  if (/gopro/.test(str)) return pick("gopro")
  if (/insta\s*360|insta360/.test(str)) return pick("insta360")
  if (/osmo/.test(str)) return pick("dji-camera")
  if (/стабилизатор|микрофон/.test(str) && /dji/.test(str)) return pick("dji-gear")
  if (/instax|fujifilm/.test(str)) return pick("instax")
  if (/airtag/.test(str)) return pick("airtag")
  if (/magic\s*mouse/.test(str)) return pick("magic-mouse")
  if (/magic\s*keyboard|клавиатура/.test(str)) return pick("magic-keyboard")
  if (/fitbit/.test(str)) return pick("fitbit")
  if (/\bpixel\b/.test(str)) return pick("pixel")
  if (/pulse/.test(str)) return pick("ps-pulse")
  if (/vr2|playstation\s*vr/.test(str)) return pick("ps-vr")
  if (/portal/.test(str)) return pick("ps-portal")
  if (/дисковод|vertical\s*stand|подставка/.test(str)) return pick("ps-stand")
  if (/mac\s*mini/.test(str)) return pick("mac-mini")
  if (/imac/.test(str)) return pick("imac")
  if (/apple\s*tv/.test(str)) return pick("apple-tv")
  if (/чехол|стекло|линз|картхолдер/.test(str)) return pick("protection")
  if (/повербанк|аккумулятор/.test(str)) return pick("powerbank")
  if (/45\s*w|45w|samsung\s*45/.test(str)) return pick("samsung-charger-45w")
  if (/переходник/.test(str)) return pick("adapters")
  if (/iphone\s*18\s*pro\s*max|айфон\s*18\s*pro\s*max/i.test(str)) return pick("iphone-18-pro-max")
  if (/iphone\s*18\s*pro|айфон\s*18\s*pro/i.test(str)) return pick("iphone-18-pro")
  if (/iphone\s*17\s*pro|айфон\s*17\s*pro/.test(str)) return pick("iphone-17-pro")
  if (/iphone\s*air|айфон\s*air/.test(str)) return pick("iphone-air")
  if (/iphone.*duo|айфон.*duo/i.test(str)) return pick("iphone-duo")
  if (/iphone\s*(17e|17\s*se)|айфон\s*(17e|17\s*se)/i.test(str)) return pick("iphone-17e")
  if (/iphone\s*17|айфон\s*17/i.test(str)) return pick("iphone-17")
  if (/macbook/.test(str)) return pick("macbook-pro")
  if (/airpods\s*max/.test(str)) return pick("airpods-max")
  if (/airpods\s*pro/.test(str)) return pick("airpods-pro")
  if (/airpods/.test(str)) return pick("airpods-5")
  if (/ipad/.test(str)) return pick("ipad-pro")
  if (/pencil/.test(str)) return pick("apple-pencil")
  if (/ray\s*ban/.test(str)) return pick("ray-ban-meta")
  if (/playstation\s*5|ps5\s*(pro|slim)/.test(str)) return pick("ps5-console")
  if (/dualsense/.test(str)) return pick("ps5-dualsense")
  if (/watch.*ultra/i.test(str) && !/galaxy|samsung/.test(str)) return pick("watch-ultra-4")
  if (/watch\s*series\s*12/.test(str) && !/galaxy|samsung/.test(str)) return pick("watch-series-12")
  if (/apple\s*watch|\bwatch\b/.test(str) && !/galaxy|samsung|fitbit/.test(str)) return pick("watch-series")
  if (/galaxy\s*z\s*fold|z\s*fold|z\s*flip/.test(str)) return pick("galaxy-z-fold8")
  if (/galaxy\s*(s25|s26|a57)|\bs26\b|\bs25\b/.test(str)) return pick("samsung-galaxy-s")
  if (/earpods|кабель|magsafe|зарядн|адаптер/.test(str)) {
    if (/samsung/.test(str)) return pick("samsung-charger-45w")
    if (/xiaomi|keephone/.test(str)) return pick("powerbank")
    return pick("apple-accessories")
  }
  if (/supersonic|nural|hd16/.test(str)) return pick("dyson-nural")
  if (/\bairwrap\b|hs08|hs09/.test(str)) return pick("dyson-airwrap")
  if (/airstrait|ht01/.test(str)) return pick("dyson-airstrait")
  if (/\bsv23\b|dyson\s*v12|\bsv50\b/.test(str)) return pick("dyson-v12")
  return null
}
